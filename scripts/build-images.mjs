// Builds responsive AVIF + WebP copies of every photograph in assets-source/photos/ into
// public/images/, a typed manifest in src/data/images.generated.ts, and one 1200x630 Open Graph
// image per page and product in public/og/. Run with: bun run images. Originals are never modified.
// Already-built sizes are skipped; delete a photograph's files in public/images/ to rebuild it.
import fs from "node:fs";
import path from "node:path";
import sharp from "sharp";

const root = path.resolve(import.meta.dirname, "..");
const SRC = path.join(root, "assets-source/photos");
const OUT = path.join(root, "public/images");
const widths = [480, 768, 1080, 1600];

/** hero-campaign.jpg -> heroCampaign */
const toId = (file) =>
  file.replace(/\.jpg$/, "").replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());

const files = fs
  .readdirSync(SRC)
  .filter((f) => f.endsWith(".jpg"))
  .sort();
fs.mkdirSync(OUT, { recursive: true });
const manifest = {};

for (const file of files) {
  const id = toId(file);
  const meta = await sharp(path.join(SRC, file)).metadata();
  const w = meta.width;
  const h = meta.height;
  const sizes = [...new Set([...widths.filter((x) => x < w), Math.min(w, widths.at(-1))])].sort(
    (a, b) => a - b,
  );
  for (const size of sizes) {
    const base = path.join(OUT, `${id}-${size}`);
    if (fs.existsSync(`${base}.avif`) && fs.existsSync(`${base}.webp`)) continue;
    const img = sharp(path.join(SRC, file)).resize({ width: size, withoutEnlargement: true });
    await img.clone().avif({ quality: 50, effort: 4 }).toFile(`${base}.avif`);
    await img.clone().webp({ quality: 76 }).toFile(`${base}.webp`);
  }
  manifest[id] = { w, h, sizes };
}

const body = `// Generated by scripts/build-images.mjs. Do not edit by hand.\nexport type ImageMeta = { w: number; h: number; sizes: number[] };\n\nexport const images = ${JSON.stringify(manifest, null, 2)} as const satisfies Record<string, ImageMeta>;\n\nexport type ImageId = keyof typeof images;\n`;
fs.writeFileSync(path.join(root, "src/data/images.generated.ts"), body);

// Open Graph images: name -> source photograph. Products use their first photograph.
const og = {
  home: "hero-campaign.jpg",
  shop: "editorial-color.jpg",
  lips: "tile-lips.jpg",
  cheeks: "tile-cheeks.jpg",
  complexion: "tile-complexion.jpg",
  about: "about-profile.jpg",
  routine: "routine-mirror.jpg",
  cart: "texture-gloss.jpg",
  checkout: "texture-gloss.jpg",
  contact: "portrait-warm.jpg",
  privacy: "texture-lip-swatch.jpg",
  terms: "texture-lip-swatch.jpg",
  "cloud-kiss-lip-treatment": "texture-gloss.jpg",
  "soft-focus-cream-blush": "portrait-freckles2.jpg",
  "skin-veil-tint": "gallery-skin.jpg",
  "dew-drop-serum": "texture-dropper.jpg",
  "everyday-glow-balm": "texture-cream.jpg",
  "the-daily-edit-set": "routine-mirror.jpg",
};
fs.mkdirSync(path.join(root, "public/og"), { recursive: true });
for (const [name, file] of Object.entries(og)) {
  await sharp(path.join(SRC, file))
    .resize(1200, 630, { fit: "cover", position: sharp.strategy.attention })
    .jpeg({ quality: 82, mozjpeg: true })
    .toFile(path.join(root, "public/og", `${name}.jpg`));
}
console.log(`built ${files.length} images and ${Object.keys(og).length} og images`);
